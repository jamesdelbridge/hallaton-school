export type WebsiteCopy = { [K in keyof typeof defaultWebsiteCopy]: string };
const copyShape = Object.fromEntries(Object.entries(defaultWebsiteCopy).map(([key, value]) => [key, z.string().trim().min(1).max(250).default(value)])) as { [K in keyof WebsiteCopy]: z.ZodDefault<z.ZodString> };
export const websiteCopyInput = z.object(copyShape).strict();

export function readWebsiteCopy(body: string | null | undefined): WebsiteCopy {
  return body == null ? { ...defaultWebsiteCopy } : websiteCopyInput.parse(JSON.parse(body));
}
